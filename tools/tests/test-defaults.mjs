import puppeteer from 'puppeteer';
const browser = await puppeteer.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'] });
const page = await browser.newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 300)); });
await page.goto(`${process.argv[2]}/editor.html?zx=0&zz=-5&size=3`, { waitUntil: 'networkidle0' });
await page.waitForFunction(() => document.querySelector('[data-count="trees"]').textContent !== '', { timeout: 120000 });
const state = await page.$$eval('[data-show]', els => els.map(e => `${e.dataset.show}:${e.checked ? 'on' : 'off'}`));
const counts = await page.$$eval('[data-count]', els => els.map(e => e.dataset.count + e.textContent));
console.log(JSON.stringify({ state, counts, errors }));
await browser.close();
